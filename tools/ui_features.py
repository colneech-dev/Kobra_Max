def in_library(i):
    """Whether picture `i` (a DWIN_SET/<i>.bmp) belongs in 16_68_.icl."""
    if i > LIBRARY_MAX_ID or i in HIDDEN_PAGES:
        return False
    if BOOT_FIRST <= i <= BOOT_LAST:
        return BOOT_ANIMATION          # only ever boot frames in this range
    return True

