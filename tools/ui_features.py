# ── 2. Values read from the firmware sources ──────────────────────────────────

def _read(path):
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""

def _define(text, name, default):
    m = re.search(r'^\s*#define\s+' + re.escape(name) + r'\s+("?[\w.]+"?)', text, re.M)
    if not m:
        return default
    v = m.group(1).strip('"')
    return int(v) if re.fullmatch(r'-?\d+', v) else v

